emitInstr :: FuncName -> Set.Set FuncName -> Text -> (Int, Instruction) -> Either String Text
emitInstr fname userFns poolName (idx, instr) = case instr of
  IPush v -> pushValue v
  IPop -> ok "  sp--;"
  IDup -> ok "  st[sp] = st[sp - 1]; sp++;"
  IBinary op ->
    ok $ "  st[sp - 2] = qt_binary(" <> binOpName op <> ", st[sp - 2], st[sp - 1]); sp--;"
  IUnary op ->
    ok $ "  st[sp - 1] = qt_unary(" <> unOpName op <> ", st[sp - 1]);"
  ILoad v -> ok $ "  st[sp++] = " <> localName v <> ";"
  IStore v -> ok $ "  " <> localName v <> " = st[--sp];"
  IJump (InstructionPointer t) -> ok $ "  goto I" <> T.pack (show t) <> ";"
  IJumpTrue (InstructionPointer t) ->
    ok $ "  if (qt_truthy(st[--sp])) goto I" <> T.pack (show t) <> ";"
  IJumpFalse (InstructionPointer t) ->
    ok $ "  if (!qt_truthy(st[--sp])) goto I" <> T.pack (show t) <> ";"
  ICall (FunctionRef target) argc
    | Set.member target userFns || Set.member (unFuncName target) supportedBuiltins ->
        ok (emitCall target argc)
    | otherwise ->
        Left $
          "native backend: unsupported builtin `"
            ++ T.unpack (unFuncName target)
            ++ "` (in function `"
            ++ T.unpack (unFuncName fname)
            ++ "` at offset "
            ++ show idx
            ++ ")"
  IRet -> ok "  return st[--sp];"
  INop -> ok "  ;"
  ICovMark _ -> ok "  ;"
  ICovBranch _ -> ok "  ;"
  INewArray -> ok "  st[sp++] = qt_array_new();"
  INewDict -> ok "  st[sp++] = qt_dict_new();"
  IArrayGet ->
    ok $
      "  { QtValue qidx = st[--sp]; QtValue qref = st[--sp];"
        <> " st[sp++] = qt_index_get(qref, qidx); }"
  IArrayGetOrNew ->
    ok $
      "  { QtValue qidx = st[--sp]; QtValue qref = st[--sp];"
        <> " st[sp++] = qt_array_get_or_new(qref, qt_want_int(qidx, \"array index\")); }"
  IArraySet ->
    ok $
      "  { QtValue qv = st[--sp]; QtValue qidx = st[--sp]; QtValue qref = st[--sp];"
        <> " qt_index_set(qref, qidx, qv); }"
  ICast CastToInt -> ok "  st[sp - 1] = qt_cast_int(st[sp - 1]);"
  ICast CastToFloat -> ok "  st[sp - 1] = qt_cast_float(st[sp - 1]);"
  ICast CastToBool -> ok "  st[sp - 1] = qt_cast_bool(st[sp - 1]);"
  ICast CastToString -> ok "  st[sp - 1] = qt_cast_string(st[sp - 1]);"
  INewStruct tname ->
    ok $ "  st[sp++] = qt_struct_new(" <> cString (unTypeName tname) <> ");"
  IFieldGet fld ->
    ok $
      "  st[sp - 1] = qt_field_get(st[sp - 1], " <> cString (unFieldName fld) <> ");"
  IFieldSet fld ->
    ok $
      "  { QtValue qv = st[--sp]; QtValue qref = st[--sp];"
        <> " qt_struct_set(qref, "
        <> cString (unFieldName fld)
        <> ", qv); }"
  INewError (ErrorName ename) fnames -> ok (emitNewError ename fnames)
  ITryOp -> ok "  if (qt_is_error(st[sp - 1])) return st[sp - 1];"
  IMustOp -> ok "  qt_must(st[sp - 1]);"
  IIsOk -> ok "  st[sp] = qt_bool(!qt_is_error(st[sp - 1])); sp++;"
  IIsErr (ErrorName ename) ->
    ok $ "  st[sp] = qt_bool(qt_error_is(st[sp - 1], " <> cString ename <> ")); sp++;"
  IDynMethodCall mname argc -> ok (emitDynCall mname argc)
  ILoadFunc target ->
    ok $ "  st[sp++] = qt_fn(" <> cString (unFuncName target) <> ");"
  IMakeClosure target capVars -> ok (emitMakeClosure target capVars)
  ICallIndirect argc -> ok (emitCallIndirect argc)
  ICallFFI lib sym retTy argc -> ok (emitFFI lib sym retTy argc)
  ISpawn (FunctionRef target) argc -> ok (emitSpawn target argc)
  IAwait -> ok "  st[sp - 1] = qt_await(st[sp - 1]);"
  where
    ok = Right
    pushValue v = case v of
      VInt n -> ok $ pushConst ("qt_int(INT64_C(" <> T.pack (show n) <> "))")
      VFloat f -> ok $ pushConst ("qt_float(" <> T.pack (showHFloat f "") <> ")")
      VBool True -> ok $ pushConst "qt_bool(1)"
      VBool False -> ok $ pushConst "qt_bool(0)"
      VStringRef i -> ok $ pushConst ("qt_string(" <> poolName <> "[" <> T.pack (show i) <> "])")
      VString s -> ok $ pushConst ("qt_string(" <> cString s <> ")")
      VUnit -> ok $ pushConst "qt_unit()"
      _ ->
        Left $
          "native backend: unsupported constant "
            ++ takeWhile (/= ' ') (show v)
            ++ " in function `"
            ++ T.unpack (unFuncName fname)
            ++ "`"
    emitCall target argc =
      let nText = T.pack (show argc)
          bufLen = T.pack (show (max 1 argc))
          gather =
            "QtValue ca["
              <> bufLen
              <> "];"
              <> " for (size_t qi = 0; qi < "
              <> nText
              <> "; qi++) { ca[qi] = st[--sp]; }"
          callExpr
            | Set.member target userFns = mangle target <> "(" <> nText <> ", ca)"
            | otherwise =
                "qt_call_builtin(" <> cString (unFuncName target) <> ", " <> nText <> ", ca)"
       in "  { " <> gather <> " st[sp++] = " <> callExpr <> "; }"
    -- Build a VErrorVal: field values were pushed in fnames order, so the
    -- last field's value is on top -- pop and assign in reverse.
    emitNewError ename fnames =
      let assigns =
            [ " qt_error_set_field(qe, " <> cString (unFieldName f) <> ", st[--sp]);"
              | f <- reverse fnames
            ]
       in "  { QtValue qe = qt_error_new("
            <> cString ename
            <> ");"
            <> T.concat assigns
            <> " st[sp++] = qe; }"
    -- Dynamic dispatch: the receiver (self) was pushed last, so it is ca[0].
    -- Its struct type plus the method name resolve the concrete function.
    emitDynCall mname argc =
      let nText = T.pack (show argc)
          bufLen = T.pack (show (max 1 argc))
       in "  { QtValue ca["
            <> bufLen
            <> "]; for (size_t qi = 0; qi < "
            <> nText
            <> "; qi++) { ca[qi] = st[--sp]; }"
            <> " char qn[256];"
            <> " snprintf(qn, sizeof(qn), \"%s."
            <> mname
            <> "\", qt_struct_type(ca[0]));"
            <> " st[sp++] = qf_dispatch(qn, "
            <> nText
            <> ", ca); }"
    -- Package a lambda's captured locals (in capture order) into a closure.
    emitMakeClosure target capVars =
      let nCaps = T.pack (show (length capVars))
          bufLen = T.pack (show (max 1 (length capVars)))
          assigns =
            [ " qc[" <> T.pack (show i) <> "] = " <> localName v <> ";"
              | (i, v) <- zip [(0 :: Int) ..] capVars
            ]
       in "  { QtValue qc["
            <> bufLen
            <> "];"
            <> T.concat assigns
            <> " st[sp++] = qt_closure("
            <> cString (unFuncName target)
            <> ", "
            <> nCaps
            <> ", qc); }"
    -- Indirect call: the callable sits just below the argc arguments.
    emitCallIndirect argc =
      let nText = T.pack (show argc)
          bufLen = T.pack (show (max 1 argc))
       in "  { QtValue ca["
            <> bufLen
            <> "]; for (size_t qi = 0; qi < "
            <> nText
            <> "; qi++) { ca[qi] = st[--sp]; }"
            <> " QtValue qcl = st[--sp];"
            <> " qt_callable_bind(qcl);"
            <> " st[sp++] = qf_dispatch(qt_callable_name(qcl), "
            <> nText
            <> ", ca); }"
    -- Foreign call: marshal args, then dispatch through the runtime FFI shim.
    emitFFI lib sym retTy argc =
      let nText = T.pack (show argc)
          bufLen = T.pack (show (max 1 argc))
          retCode = case retTy of
            CRetVoid -> "0"
            CRetInt -> "1"
            CRetFloat -> "2"
            CRetStr -> "3"
            CRetBool -> "4"
            CRetPtr -> "5"
       in "  { QtValue ca["
            <> bufLen
            <> "]; for (size_t qi = 0; qi < "
            <> nText
            <> "; qi++) { ca[qi] = st[--sp]; }"
            <> " st[sp++] = qt_ffi_call("
            <> cString lib
            <> ", "
            <> cString sym
            <> ", "
            <> retCode
            <> ", "
            <> nText
            <> ", ca); }"
    -- Spawn an async task: queue the function without transferring control.
    emitSpawn target argc =
      let nText = T.pack (show argc)
          bufLen = T.pack (show (max 1 argc))
       in "  { QtValue ca["
            <> bufLen
            <> "]; for (size_t qi = 0; qi < "
            <> nText
            <> "; qi++) { ca[qi] = st[--sp]; }"
            <> " st[sp++] = qt_spawn("
            <> cString (unFuncName target)
            <> ", "
            <> nText
            <> ", ca); }"

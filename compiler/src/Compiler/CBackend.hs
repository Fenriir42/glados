import Numeric (showHFloat, showOct)

-- | Translate compiled bytecode into a standalone C translation unit
-- (to be compiled against runtime/quant_runtime.{h,c}).
emitC :: [Bytecode] -> Either String Text
emitC bcs
  | FuncName "main" `notElem` map bytecodeFunction bcs =
      Left "native backend: program has no `main` function"
  | otherwise = do
      let userFns = Set.fromList (map bytecodeFunction bcs)
          captures = capturesOf bcs
      funcs <- mapM (emitFunction userFns captures) bcs
      Right $
        T.unlines $
          [ "/* Generated by glados --native; do not edit. */",
            "#include \"quant_runtime.h\"",
            "#include <stdio.h>",
            "#include <string.h>",
            ""
          ]
            ++ map protoLine bcs
            ++ [""]
            ++ dispatchFn bcs
            ++ funcs
            ++ [ "int main(int argc, char **argv) {",
                 "    qt_set_args(argc, argv);",
                 "    qt_set_dispatch(qf_dispatch);",
                 mainCall,
                 "    return 0;",
                 "}"
               ]
  where
    usesAsync = any (any isAsyncInstr . bytecodeInstructions) bcs
    -- Async programs drive `main` through the cooperative scheduler (as task
    -- 0); everything else calls it directly on the process stack.
    mainCall
      | usesAsync = "    qt_async_run(" <> cString "main" <> ");"
      | otherwise = "    " <> mangle (FuncName "main") <> "(0, (const QtValue *)0);"
    protoLine bc =
      "static QtValue "
        <> mangle (bytecodeFunction bc)
        <> "(size_t argc, const QtValue *args);"

-- | Instructions that require the async runtime (drive `main` via the scheduler).
isAsyncInstr :: Instruction -> Bool
isAsyncInstr (ISpawn _ _) = True
isAsyncInstr IAwait = True
isAsyncInstr _ = False

-- | Resolve an @IDynMethodCall@'s @Type.method@ name to the concrete C
-- function at runtime.  The receiver's struct type + the method name form
-- the key; this if-chain is the native equivalent of the VM's
-- @vmStructTypes@-driven dispatch.
dispatchFn :: [Bytecode] -> [Text]
dispatchFn bcs =
  [ "static QtValue qf_dispatch(const char *name, size_t argc, const QtValue *args) {"
  ]
    ++ [ "    if (strcmp(name, "
           <> cString (unFuncName f)
           <> ") == 0) return "
           <> mangle f
           <> "(argc, args);"
         | f <- map bytecodeFunction bcs
       ]
    ++ [ "    qt_panic(\"native backend: no method for dynamic dispatch\");",
         "}",
         ""
       ]

-- | C identifier for a Quant function name ('.' becomes "__").
mangle :: FuncName -> Text
mangle (FuncName n) = "qf_" <> T.concatMap mangleChar n
  where
    mangleChar '.' = "__"
    mangleChar c
      | isAscii c && isAlphaNum c = T.singleton c
      | otherwise = "_x" <> T.pack (show (ord c)) <> "_"

localName :: VarName -> Text
localName (VarName n) = "l_" <> T.concatMap mangleChar n
  where
    mangleChar '.' = "__"
    mangleChar c
      | isAscii c && isAlphaNum c = T.singleton c
      | otherwise = "_x" <> T.pack (show (ord c)) <> "_"

-- | C string literal with octal escapes for anything non-printable.
cString :: Text -> Text
cString t = "\"" <> T.concatMap esc t <> "\""
  where
    esc '"' = "\\\""
    esc '\\' = "\\\\"
    esc '\n' = "\\n"
    esc '\r' = "\\r"
    esc '\t' = "\\t"
    esc c
      | isAscii c && ord c >= 0x20 && ord c < 0x7f = T.singleton c
      | otherwise = octEsc c
    -- Encode as UTF-8 bytes, each as a fixed-width octal escape (safe
    -- against following digit characters, unlike hex escapes).
    octEsc c = T.concat [T.pack ("\\" ++ pad (showOct b "")) | b <- utf8Bytes (ord c)]
    pad s = replicate (3 - length s) '0' ++ s
    utf8Bytes cp
      | cp < 0x80 = [cp]
      | cp < 0x800 = [0xc0 + cp `div` 64, 0x80 + cp `mod` 64]
      | cp < 0x10000 =
          [0xe0 + cp `div` 4096, 0x80 + (cp `div` 64) `mod` 64, 0x80 + cp `mod` 64]
      | otherwise =
          [ 0xf0 + cp `div` 262144,
            0x80 + (cp `div` 4096) `mod` 64,
            0x80 + (cp `div` 64) `mod` 64,
            0x80 + cp `mod` 64
          ]

-- | Map every closure body to its captured variables (in IMakeClosure
-- order), so the generated function can read them back from qt_env at entry.
capturesOf :: [Bytecode] -> Map.Map FuncName [VarName]
capturesOf bcs =
  Map.fromList
    [ (target, capVars)
      | bc <- bcs,
        IMakeClosure target capVars <- bytecodeInstructions bc
    ]

emitFunction :: Set.Set FuncName -> Map.Map FuncName [VarName] -> Bytecode -> Either String Text
emitFunction userFns captures bc = do
  let fname = bytecodeFunction bc
      instrs = bytecodeInstructions bc
      pool = bytecodeStrings bc
      poolName = "P_" <> mangle fname
      targets = Set.fromList (concatMap jumpTargets instrs)
      locals = nub (concatMap localsOf instrs)
      capVars = Map.findWithDefault [] fname captures
  bodies <- mapM (emitInstr fname userFns poolName) (zip [0 ..] instrs)
  let numbered =
        [ (if Set.member i targets then "  I" <> T.pack (show i) <> ": ;\n" else "")
            <> body
          | (i, body) <- zip [(0 :: Int) ..] bodies
        ]
      poolDef
        | null pool = []
        | otherwise =
            [ "static const char *"
                <> poolName
                <> "[] = {"
                <> T.intercalate ", " (map cString pool)
                <> "};"
            ]
  Right $
    T.unlines $
      poolDef
        ++ [ "static QtValue " <> mangle fname <> "(size_t argc, const QtValue *args) {",
             "  (void)argc; (void)args;",
             "  QtValue st[" <> T.pack (show (length instrs + 8)) <> "];",
             "  size_t sp = 0;"
           ]
        ++ ["  QtValue " <> localName v <> " = qt_unit();" | v <- locals]
        ++ ["  (void)" <> localName v <> ";" | v <- locals]
        ++ [ "  for (size_t qi = argc; qi > 0; qi--) { st[sp++] = args[qi - 1]; }"
           ]
        -- Seed captured locals from the bound closure environment (stage 7).
        ++ [ "  " <> localName v <> " = qt_env(" <> T.pack (show i) <> ");"
             | (i, v) <- zip [(0 :: Int) ..] capVars
           ]
        ++ numbered
        ++ [ "  return qt_unit();",
             "}"
           ]

jumpTargets :: Instruction -> [Int]
jumpTargets (IJump (InstructionPointer t)) = [t]
jumpTargets (IJumpTrue (InstructionPointer t)) = [t]
jumpTargets (IJumpFalse (InstructionPointer t)) = [t]
jumpTargets _ = []

localsOf :: Instruction -> [VarName]
localsOf (ILoad v) = [v]
localsOf (IStore v) = [v]
localsOf _ = []

binOpName :: BinaryOp -> Text
binOpName op = case op of
  BOpAdd -> "QT_BOP_ADD"
  BOpSub -> "QT_BOP_SUB"
  BOpMul -> "QT_BOP_MUL"
  BOpDiv -> "QT_BOP_DIV"
  BOpMod -> "QT_BOP_MOD"
  BOpEq -> "QT_BOP_EQ"
  BOpNeq -> "QT_BOP_NEQ"
  BOpLt -> "QT_BOP_LT"
  BOpLte -> "QT_BOP_LTE"
  BOpGt -> "QT_BOP_GT"
  BOpGte -> "QT_BOP_GTE"
  BOpAnd -> "QT_BOP_AND"
  BOpOr -> "QT_BOP_OR"
  BOpBitAnd -> "QT_BOP_BITAND"
  BOpBitOr -> "QT_BOP_BITOR"
  BOpBitXor -> "QT_BOP_BITXOR"
  BOpShl -> "QT_BOP_SHL"
  BOpShr -> "QT_BOP_SHR"

unOpName :: UnaryOp -> Text
unOpName UOpNot = "QT_UOP_NOT"
unOpName UOpNeg = "QT_UOP_NEG"
unOpName UOpBitNot = "QT_UOP_BITNOT"

pushConst :: Text -> Text
pushConst expr = "  st[sp++] = " <> expr <> ";"

